#!/usr/bin/env node
// Protocol registry tooling.
//   node scripts/registry.mjs check   validate every registry/protocols/*.json against registry/SCHEMA.md rules
//   node scripts/registry.mjs index   regenerate src/lib/mcp/registryData.ts (the files the MCP serves)
// `index` runs `check` first and refuses to write if a file is invalid.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getAddress } from 'viem';

const DIR = 'registry/protocols';
const OUT = 'src/lib/mcp/registryData.ts';
const VMS = new Set(['evm', 'solana', 'ton', 'hyperliquid-l1', 'mixed']);
const ACCESS = new Set(['onchain', 'api', 'both']);

function check() {
  const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
  const errors = [];
  const entries = [];
  for (const f of files) {
    const err = (m) => errors.push(`${f}: ${m}`);
    let p;
    try { p = JSON.parse(readFileSync(join(DIR, f), 'utf8')); } catch (e) { err(`invalid JSON (${e.message})`); continue; }
    if (`${p.slug}.json` !== f) err(`slug "${p.slug}" does not match the file name`);
    for (const k of ['name', 'category', 'description']) if (typeof p[k] !== 'string' || !p[k]) err(`missing ${k}`);
    if (!VMS.has(p.vm)) err(`vm must be one of ${[...VMS].join(', ')}`);
    if (!ACCESS.has(p.agentAccess)) err(`agentAccess must be one of ${[...ACCESS].join(', ')}`);
    if (!Array.isArray(p.contracts)) err('contracts must be an array');
    for (const [i, c] of (p.contracts ?? []).entries()) {
      const at = `contracts[${i}] ${c.name ?? ''}@${c.chain ?? '?'}`;
      if (!c.chain || !c.address || !c.name) err(`${at}: chain, address and name are required`);
      if (!/^https?:\/\//.test(c.source ?? '')) err(`${at}: source URL required`);
      if (typeof c.chainId === 'number') {
        try { if (getAddress(c.address) !== c.address) c.address = getAddress(c.address); }
        catch { err(`${at}: "${c.address}" is not a valid EVM address`); }
      }
      for (const fn of c.keyFunctions ?? []) if (!fn.signature || !['read', 'write'].includes(fn.kind)) err(`${at}: keyFunction needs signature and kind read|write`);
    }
    entries.push(p);
  }
  return { files, errors, entries };
}

const cmd = process.argv[2] ?? 'check';
const { files, errors, entries } = check();
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
console.log(`${files.length} protocol files OK, ${entries.reduce((n, p) => n + p.contracts.length, 0)} contracts`);
if (cmd === 'index') {
  const body = `// Generated by \`node scripts/registry.mjs index\` from registry/protocols/*.json. Do not edit by hand.\n` +
    `import type { ProtocolEntry } from './registry';\n\n` +
    `export const PROTOCOLS: ProtocolEntry[] = ${JSON.stringify(entries, null, 1)};\n`;
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}`);
  // The same list for the Rust API (api-rs), compiled into its binary.
  mkdirSync('api-rs/data', { recursive: true });
  writeFileSync('api-rs/data/registry.json', JSON.stringify(entries));
  console.log('wrote api-rs/data/registry.json');
}
